def render(e):
    cid, brand, site, email, greet, subject, obs, idea = e
    return subject, TEMPLATE.format(greet=greet, obs=obs, idea=idea)


def check(e):
    """Problems with one email: length, dashes, the idea prefix, words that read as machine-written."""
    s, body = render(e)
    out = []
    words = len(body.split())
    if words > 93: out.append(f'{words} words')
    if re.search('[–—]', s + body): out.append('en/em dash')
    if not e[7].startswith('An idea: '): out.append('idea prefix')
    if re.search(r'\b(elevate|leverage|unlock|game.?changer|seamless|delve|robust|synergy|boost your)\b', body, re.I): out.append('slop word')
    if len(s.split()) > 7: out.append('long subject')
    return out


